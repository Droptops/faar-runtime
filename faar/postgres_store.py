class _EmptyCursor:
    rowcount = 0

    def fetchone(self) -> None:
        return None

    def fetchall(self) -> list[Any]:
        return []


def _postgres_sql(sql: str) -> str:
    """Translate the reference store's narrow SQLite SQL dialect.

    Question marks are replaced only outside quoted SQL literals.  The two
    ``rowid`` references encode permit issuance order and map to the explicit
    PostgreSQL identity column.
    """
    sql = sql.replace("rowid,* FROM execution_permits", "issuance_seq AS rowid,* FROM execution_permits")
    sql = sql.replace("AND rowid > ?", "AND issuance_seq > ?")
    out: list[str] = []
    quoted = False
    index = 0
    while index < len(sql):
        char = sql[index]
        if char == "'":
            out.append(char)
            if quoted and index + 1 < len(sql) and sql[index + 1] == "'":
                out.append("'")
                index += 2
                continue
            quoted = not quoted
        elif char == "?" and not quoted:
            out.append("%s")
        else:
            out.append(char)
        index += 1
    return "".join(out)


class _PostgresConnection:
    """Small compatibility surface used by ``SQLiteIntentStore`` methods."""

    def __init__(self, raw: Any, psycopg_module: Any, writer_lock_name: str) -> None:
        self.raw = raw
        self.psycopg = psycopg_module
        self.writer_lock_name = writer_lock_name

    def _raise_driver_error(self, exc: BaseException) -> None:
        if isinstance(exc, self.psycopg.IntegrityError):
            constraint = getattr(getattr(exc, "diag", None), "constraint_name", None)
            detail = f"{constraint}: {exc}" if constraint else str(exc)
            raise sqlite3.IntegrityError(detail) from exc
        if isinstance(exc, (self.psycopg.OperationalError, self.psycopg.InterfaceError)):
            raise StoreUnavailable("PostgreSQL datastore unavailable") from exc
        if isinstance(exc, self.psycopg.Error):
            raise StoreUnavailable("PostgreSQL datastore operation failed") from exc
        raise exc

    def execute(self, sql: str, params: tuple[Any, ...] | list[Any] = ()) -> Any:
        statement = sql.strip()
        try:
            if statement == "BEGIN IMMEDIATE":
                self.raw.execute("BEGIN")
                try:
                    return self.raw.execute(
                        "SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))",
                        (self.writer_lock_name,),
                    )
                except BaseException:
                    # Acquiring the writer lock happens before inherited methods
                    # enter their try/finally transaction body. Roll back here so a
                    # timeout cannot strand the connection in an aborted txn.
                    try:
                        self.raw.execute("ROLLBACK")
                    except BaseException:
                        pass
                    raise
            if statement == "BEGIN":
                return self.raw.execute("BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY")
            if statement == "ROLLBACK" and self.raw.closed:
                return _EmptyCursor()
            if statement.startswith("PRAGMA "):
                return _EmptyCursor()
            return self.raw.execute(_postgres_sql(sql), params)
        except BaseException as exc:
            # Preserve the original failure if a broken connection cannot accept
            # the cleanup ROLLBACK issued by the inherited transaction body.
            if statement == "ROLLBACK":
                return _EmptyCursor()
            self._raise_driver_error(exc)
            raise AssertionError("unreachable")

    def executescript(self, script: str) -> None:
        self.execute("BEGIN IMMEDIATE")
        try:
            for statement in script.split(";"):
                if statement.strip():
                    self.execute(statement)
            self.execute("COMMIT")
        except BaseException:
            self.execute("ROLLBACK")
            raise

    def close(self) -> None:
        self.raw.close()


class PostgresIntentStore(SQLiteIntentStore):
    """PostgreSQL 16 store reproducing ``STORE_CONTRACT.md`` semantics.

    ``schema`` is an explicit namespace so test and deployment instances cannot
    accidentally share ledgers.  The constructor creates that schema only when
    it is absent; opening a current store performs read-only schema/index probes.
    """

    _POSTGRES_COLUMN_MIGRATIONS = SQLiteIntentStore._COLUMN_MIGRATIONS + (
        ("execution_permits", "issuance_seq", "BIGINT GENERATED BY DEFAULT AS IDENTITY"),
    )
    _POSTGRES_BIGINT_COLUMNS = {
        "grants": {"version", "runtime_epoch", "fence_counter"},
        "usage_reservations": {"grant_version", "velocity_bucket", "velocity_ts"},
        "risk_claims": {"grant_version", "state_version"},
        "permit_risk_claims": {"grant_version", "state_version"},
        "intents": {"submission_count"},
        "evidence_head": {"seq"},
        "runtime_controls": {"control_epoch"},
        "execution_permits": {"grant_version", "grant_epoch", "fence_token", "issuance_seq"},
    }

    def __init__(
        self,
        dsn: str,
        *,
        schema: str = "faar",
        evidence_key: bytes | None = None,
        authority_anchor: AuthorityAnchor | None = None,
    ) -> None:
        if not isinstance(dsn, str) or not dsn:
            raise ValueError("a PostgreSQL DSN is required")
        if not isinstance(schema, str) or _SCHEMA_RE.fullmatch(schema) is None:
            raise ValueError("PostgreSQL schema must match [a-z][a-z0-9_]{0,62}")
        try:
            import psycopg
            from psycopg import sql as pg_sql
            from psycopg.rows import dict_row
        except ImportError as exc:  # pragma: no cover - exercised without the optional extra
            raise RuntimeError("install faar-runtime[postgres] to use PostgresIntentStore") from exc

        self.path = f"postgresql:<redacted>/{schema}"
        self._dsn = dsn
        self._schema = schema
        self._psycopg = psycopg
        self._pg_sql = pg_sql
        self._anchor = authority_anchor
        self._lock = threading.RLock()
        self._intent_lock_guard = threading.Lock()
        self._intent_locks = {}
        self._intent_guard_local = threading.local()
        self._host = socket.gethostname()
        self._instance_id = uuid.uuid4().hex
        self._evidence_key = bytes(evidence_key) if evidence_key is not None else None
        if self._evidence_key is not None and len(self._evidence_key) < 16:
            raise ValueError("evidence_key must be at least 16 bytes")

        try:
            raw = psycopg.connect(
                dsn,
                autocommit=True,
                row_factory=dict_row,
                connect_timeout=10,
                application_name="faar-runtime",
            )
            raw.execute("SET lock_timeout = '30s'")
            raw.execute("SET statement_timeout = '60s'")
            raw.execute("SET synchronous_commit = on")
            self._ensure_namespace(raw)
            raw.execute(pg_sql.SQL("SET search_path TO {}, public").format(pg_sql.Identifier(schema)))
            database = str(raw.execute("SELECT current_database() AS name").fetchone()["name"])
        except psycopg.Error as exc:
            if "raw" in locals():
                raw.close()
            raise StoreUnavailable("PostgreSQL datastore initialization failed") from exc

        scope_material = f"{database}\x1f{schema}".encode("utf-8")
        self._fence_scope = "postgres:" + hashlib.sha256(scope_material).hexdigest()
        writer_lock_name = f"faar:{database}:{schema}:writer:v1"
        self._conn = _PostgresConnection(raw, psycopg, writer_lock_name)

        try:
            self._migrate_columns()
            self._create_dependent_indexes()
            self._bind_anchor_setting()
            self._bind_heads_since()
        except BaseException:
            raw.close()
            raise

    def _ensure_namespace(self, raw: Any) -> None:
        exists = raw.execute(
            "SELECT 1 FROM pg_namespace WHERE nspname=%s", (self._schema,)
        ).fetchone()
        if exists is not None:
            return
        raw.execute("BEGIN")
        try:
            raw.execute(
                "SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))",
                (f"faar:schema:{self._schema}:v1",),
            )
            raw.execute(
                self._pg_sql.SQL("CREATE SCHEMA IF NOT EXISTS {}").format(
                    self._pg_sql.Identifier(self._schema)
                )
            )
            raw.execute("COMMIT")
        except BaseException:
            raw.execute("ROLLBACK")
            raise

    def _table_exists(self, table: str) -> bool:
        return self._conn.execute("SELECT to_regclass(%s) AS name", (table,)).fetchone()["name"] is not None

    def _migrate_columns(self) -> None:
        stamped = None
        backend = None
        if self._table_exists("store_settings"):
            stamped = self._conn.execute(
                "SELECT value FROM store_settings WHERE key='schema_revision'"
            ).fetchone()
            backend = self._conn.execute(
                "SELECT value FROM store_settings WHERE key='backend'"
            ).fetchone()
        if (
            stamped is not None
            and str(stamped["value"]) == POSTGRES_SCHEMA_REVISION
            and backend is not None
            and str(backend["value"]) == POSTGRES_BACKEND_ID
        ):
            return

        self._conn.execute("BEGIN IMMEDIATE")
        try:
            for statement in _POSTGRES_SCHEMA.split(";"):
                if statement.strip():
                    self._conn.execute(statement)
            for table, column, definition in self._POSTGRES_COLUMN_MIGRATIONS:
                present = self._conn.execute(
                    "SELECT 1 FROM information_schema.columns "
                    "WHERE table_schema=current_schema() AND table_name=? AND column_name=?",
                    (table, column),
                ).fetchone()
                if present is None:
                    # Identifiers and definitions are compile-time constants above.
                    self._conn.execute(f"ALTER TABLE {table} ADD COLUMN {column} {definition}")
            for table, columns in self._POSTGRES_BIGINT_COLUMNS.items():
                for column in columns:
                    kind = self._conn.execute(
                        "SELECT data_type FROM information_schema.columns "
                        "WHERE table_schema=current_schema() AND table_name=? AND column_name=?",
                        (table, column),
                    ).fetchone()
                    if kind is not None and str(kind["data_type"]) != "bigint":
                        self._conn.execute(
                            f"ALTER TABLE {table} ALTER COLUMN {column} TYPE BIGINT"
                        )
            self._backfill_legacy_rows_locked()
            self._create_dependent_indexes_locked()
            existing_backend = self._conn.execute(
                "SELECT value FROM store_settings WHERE key='backend'"
            ).fetchone()
            if existing_backend is not None and str(existing_backend["value"]) != POSTGRES_BACKEND_ID:
                raise MigrationError("store_settings.backend is not postgresql16")
            if existing_backend is None:
                self._conn.execute(
                    "INSERT INTO store_settings(key,value,updated_at) VALUES('backend',?,?)",
                    (POSTGRES_BACKEND_ID, self._now()),
                )
            self._conn.execute(
                "INSERT INTO store_settings(key,value,updated_at) VALUES('schema_revision',?,?) "
                "ON CONFLICT(key) DO UPDATE SET value=excluded.value, updated_at=excluded.updated_at",
                (POSTGRES_SCHEMA_REVISION, self._now()),
            )
            self._conn.execute("COMMIT")
        except BaseException as exc:
            self._conn.execute("ROLLBACK")
            if isinstance(exc, (sqlite3.IntegrityError, StoreUnavailable, MigrationError)):
                raise
            raise MigrationError("PostgreSQL schema migration failed") from exc

    def _create_dependent_indexes(self) -> None:
        expected = {
            "ix_usage_grant_velocity_ts",
            "ix_usage_principal_velocity_ts",
            "ix_evidence_intent_id",
            "ix_permits_intent",
            "ix_usage_velocity_status",
            "ux_effect_id_per_venue",
            "ux_execution_permits_issuance_seq",
        }
        rows = self._conn.execute(
            "SELECT indexname AS name FROM pg_indexes WHERE schemaname=current_schema()"
        ).fetchall()
        if expected.issubset({str(row["name"]) for row in rows}):
            return
        self._conn.execute("BEGIN IMMEDIATE")
        try:
            self._create_dependent_indexes_locked()
            self._conn.execute("COMMIT")
        except BaseException:
            self._conn.execute("ROLLBACK")
            raise

    def _create_dependent_indexes_locked(self) -> None:
        super()._create_dependent_indexes_locked()
        self._conn.execute(
            "CREATE UNIQUE INDEX IF NOT EXISTS ux_execution_permits_issuance_seq "
            "ON execution_permits(issuance_seq)"
        )

    @contextmanager
    def execution_guard(self, grant_id: str, version: int) -> Iterator[None]:
        """Serialize local submitters without blocking cross-host emergency stops.

        Cross-host ordering is provided by the transaction lock plus the durable
        grant epoch checked by permit consumption.  Holding a database/session lock
        across an external adapter call would let a hung venue block revocation.
        """
        lock = self._grant_lock(grant_id, version)
        with lock:
            yield

    def clear_stale_intent_lease(
        self,
        intent_id: str,
        *,
        expected_owner_token: str,
        force: bool = False,
    ) -> bool:
        with self._lock:
            self._conn.execute("BEGIN IMMEDIATE")
            try:
                row = self._conn.execute(
                    "SELECT owner_token,host,pid FROM intent_leases WHERE intent_id=?",
                    (intent_id,),
                ).fetchone()
                if row is None or str(row["owner_token"]) != expected_owner_token:
                    self._conn.execute("COMMIT")
                    return False
                if (
                    not force
                    and row["pid"] is not None
                    and row["host"] == self._host
                    and self._pid_alive(row["pid"])
                ):
                    raise LeaseOwnerAlive(
                        f"lease for {intent_id} is held by live process {row['pid']} "
                        f"on {row['host']}; refuse unless forced"
                    )
                deleted = self._conn.execute(
                    "DELETE FROM intent_leases WHERE intent_id=? AND owner_token=?",
                    (intent_id, expected_owner_token),
                ).rowcount == 1
                self._conn.execute("COMMIT")
                return deleted
            except BaseException:
                self._conn.execute("ROLLBACK")
                raise

    def checkpoint(self, *, attempts: int = 10) -> bool:
        """Confirm connectivity; PostgreSQL backup/WAL management is external.

        PostgreSQL commits use ``synchronous_commit=on`` on this connection.  This
        method is not an instruction to copy database files and does not replace a
        managed backup/failover procedure.
        """
        del attempts
        with self._lock:
            self._conn.execute("SELECT 1").fetchone()
        return True


