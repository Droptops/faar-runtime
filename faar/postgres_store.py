from __future__ import annotations

"""PostgreSQL 16 implementation of the FAAR store contract.

The state-machine implementation lives in :mod:`faar.store`.  This backend
supplies the same DB-API surface while replacing SQLite's global
``BEGIN IMMEDIATE`` writer lock with a transaction-scoped PostgreSQL advisory
lock.  That deliberately conservative lock preserves the reference store's
linearization order for aggregate budgets, authority changes, permits, intent
CAS operations, and evidence appends across hosts.

No connection string is included in diagnostics: production DSNs commonly
contain credentials and must be supplied by the deployment's secret channel.
"""

